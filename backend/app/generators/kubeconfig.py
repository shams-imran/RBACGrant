"""Kubeconfig assembly."""
from __future__ import annotations

import io
from datetime import datetime, timedelta, timezone

from ruamel.yaml import YAML


def build_kubeconfig(*, cluster_name: str, server_url: str, ca_data_b64: str,
                     user_name: str, context_name: str | None = None,
                     namespace: str | None = None,
                     token: str | None = None,
                     client_cert_b64: str | None = None,
                     client_key_b64: str | None = None,
                     expires_at: datetime | None = None) -> str:
    user: dict = {}
    if token:
        user["token"] = token
    if client_cert_b64:
        user["client-certificate-data"] = client_cert_b64
    if client_key_b64:
        user["client-key-data"] = client_key_b64

    context = {"cluster": cluster_name, "user": user_name}
    if namespace:
        context["namespace"] = namespace

    cfg = {
        "apiVersion": "v1",
        "kind": "Config",
        "clusters": [{
            "name": cluster_name,
            "cluster": {"server": server_url, "certificate-authority-data": ca_data_b64},
        }],
        "users": [{"name": user_name, "user": user}],
        "contexts": [{"name": context_name or f"{user_name}@{cluster_name}",
                      "context": context}],
        "current-context": context_name or f"{user_name}@{cluster_name}",
    }
    yaml = YAML(typ="safe", pure=True)
    yaml.default_flow_style = False
    buf = io.StringIO()
    # A YAML comment states the expiry.
    buf.write("# Generated by k8s-rbac-builder. This file contains credentials — protect it.\n")
    if expires_at:
        buf.write(f"# Credentials expire at {expires_at.isoformat(timespec='seconds')}\n")
    yaml.dump(cfg, buf)
    return buf.getvalue()


def kubeconfig_filename(cluster: str, subject: str, expires_at: datetime | None) -> str:
    stamp = expires_at.strftime("%Y%m%dT%H%M%SZ") if expires_at else "no-expiry"
    subject_safe = subject.replace(":", "_").replace("/", "_")
    return f"kubeconfig-{cluster}-{subject_safe}-exp{stamp}.yaml"


def expiry_from_ttl(ttl_seconds: int) -> datetime:
    return datetime.now(timezone.utc) + timedelta(seconds=ttl_seconds)
