// The private key is generated in the browser (WebCrypto, ECDSA
// P-256). Only the CSR goes to the server; the kubeconfig is assembled here,
// so the key never leaves this page. WebCrypto requires a secure context,
// which the server's http://127.0.0.1-or-https rule already guarantees.
import * as x509 from '@peculiar/x509';

x509.cryptoProvider.set(crypto);

export function webCryptoAvailable(): boolean {
  return typeof crypto !== 'undefined' && !!crypto.subtle;
}

export interface GeneratedCsr {
  csrPem: string;
  privateKeyPem: string;
}

export async function generateKeyAndCsr(
  commonName: string, groups: string[],
): Promise<GeneratedCsr> {
  const alg = { name: 'ECDSA', namedCurve: 'P-256', hash: 'SHA-256' };
  const keys = await crypto.subtle.generateKey(alg, true, ['sign', 'verify']);

  // CN = username, O = groups.
  const dn = [
    ...groups.map((g) => `O=${g.replace(/([,+"\\<>;=])/g, '\\$1')}`),
    `CN=${commonName.replace(/([,+"\\<>;=])/g, '\\$1')}`,
  ].join(', ');

  const csr = await x509.Pkcs10CertificateRequestGenerator.create({
    name: dn,
    keys,
    signingAlgorithm: alg,
  });

  const pkcs8 = await crypto.subtle.exportKey('pkcs8', keys.privateKey);
  const privateKeyPem = toPem(pkcs8, 'PRIVATE KEY');
  return { csrPem: csr.toString('pem'), privateKeyPem };
}

function toPem(buf: ArrayBuffer, label: string): string {
  const b64 = btoa(String.fromCharCode(...new Uint8Array(buf)));
  const lines = b64.match(/.{1,64}/g) ?? [];
  return `-----BEGIN ${label}-----\n${lines.join('\n')}\n-----END ${label}-----\n`;
}

export function b64(text: string): string {
  return btoa(unescape(encodeURIComponent(text)));
}

// Client-side kubeconfig assembly: cert + key stay in the browser.
export function assembleUserKubeconfig(opts: {
  clusterName: string; serverUrl: string; caDataB64: string;
  userName: string; certPem: string; keyPem: string;
  defaultNamespace?: string | null; expiresAt: string;
}): string {
  const ctx = `${opts.userName}@${opts.clusterName}`;
  const nsLine = opts.defaultNamespace ? `\n    namespace: ${opts.defaultNamespace}` : '';
  return `# Generated by RBACGrant IN YOUR BROWSER — the private key never touched the server.
# This file contains credentials — protect it. Certificate expires at ${opts.expiresAt}.
apiVersion: v1
kind: Config
clusters:
- name: ${opts.clusterName}
  cluster:
    server: ${opts.serverUrl}
    certificate-authority-data: ${opts.caDataB64}
users:
- name: ${opts.userName}
  user:
    client-certificate-data: ${b64(opts.certPem)}
    client-key-data: ${b64(opts.keyPem)}
contexts:
- name: ${ctx}
  context:
    cluster: ${opts.clusterName}
    user: ${opts.userName}${nsLine}
current-context: ${ctx}
`;
}
